/* =============================================================================
 * auth_db.h
 *
 * Gateway Authentication Database
 *
 * Responsibilities:
 *   - Maintain whitelist of authorized devices (TID)
 *   - Register devices and assign CRC32 as unique identifier
 *   - Store authentication context per device (CW, RW, state, history)
 *   - Resolve CRC32 -> TID for incoming frames
 * ============================================================================= */

#ifndef AUTH_DB_H
#define AUTH_DB_H

#include <stdint.h>
#include <stdbool.h>

/* ===================== CONFIGURATION ===================== */
#define AUTH_DB_MAX_DEVICES     100
#define AUTH_DB_TID_HEX_LEN     64
#define AUTH_DB_CW_HEX_LEN      64
#define AUTH_DB_RW_HEX_LEN      32

/* ===================== WHITELIST =====================
 * Read-only list of authorized TIDs.
 * Configured in auth_db_whitelist.c
 * ===================================================== */
extern const char    *auth_db_whitelist[];
extern uint16_t       auth_db_whitelist_count;   /* mutable - set by auth_db_load_whitelist() */

/* Load the authorized-TID whitelist from a plain-text file (one 64-hex TID per
 * line). Path defaults to GW_WHITELIST_PATH env or ./trustbridge_whitelist.txt.
 * Returns the number of TIDs loaded. Defined in auth_db_whitelist.c. */
int auth_db_load_whitelist(const char *file_path);

/* ===================== CACHE-MISS HOOK =====================
 * Optional callback the application can register to be notified when
 * auth_db_resolve() / auth_db_find_by_crc32() can't find a CRC32 in the
 * current cache. The callback gets a chance to refresh the whitelist
 * (e.g. fetch from a backend) before the lookup ultimately fails.
 *
 * Return: the new whitelist_count after the refresh (or 0 to skip retry).
 * If the count grew and the missing CRC32 is now present, auth_db will
 * resolve on its retry instead of returning NOT_FOUND.
 *
 * Used by main_gw.c to bypass the race where a device is enrolled in
 * TrustBridge a moment before its first auth attempt arrives - the
 * gateway's 3s polling refresh would otherwise miss the window.
 * ============================================================ */
typedef int (*auth_db_miss_handler_t)(uint32_t missing_crc32);
void auth_db_set_miss_handler(auth_db_miss_handler_t handler);

/* ===================== AUTH STATE ===================== */
typedef enum {
    AUTH_STATE_IDLE = 0,
    AUTH_STATE_CW_SENT,
    AUTH_STATE_RW_RECEIVED,
    AUTH_STATE_SERVER_VERIFIED,
    AUTH_STATE_DONE
} auth_state_t;

/* ===================== AUTH RESULT ===================== */
typedef enum {
    AUTH_RESULT_NONE = 0,
    AUTH_RESULT_OK,
    AUTH_RESULT_NOK
} auth_result_t;

/* ===================== AUTH CONTEXT =====================
 * Per-device authentication context.
 * Created when a device starts authentication,
 * updated at each step, preserved as history.
 * ===================================================== */
typedef struct {
    uint32_t      crc32;                              /* CRC32 of TID - device identifier    */
    char          tid_hex[AUTH_DB_TID_HEX_LEN + 1];  /* Full TID hex string                 */
    uint8_t       cw[32];                             /* CW generated by GW                  */
    uint8_t       rw_device[16];                      /* RW computed by DEVICE               */
    uint8_t       rw_server[16];                      /* RW returned by SERVER               */
    auth_state_t  state;                              /* Current authentication state        */
    auth_result_t result;                             /* Final authentication result         */
    int           cw_bit_diff;                        /* Bit difference CW1 vs CW2           */
    int           rw_bit_diff;                        /* Bit difference RW1 vs RW2           */
    uint32_t      timestamp;                          /* Epoch time when auth started        */
} auth_ctx_t;

/* ===================== STATUS ===================== */
typedef enum {
    AUTH_DB_OK             = 0,
    AUTH_DB_NOT_FOUND      = 1,
    AUTH_DB_ALREADY_ACTIVE = 2,
    AUTH_DB_FULL           = 3,
    AUTH_DB_ERROR          = 4
} auth_db_status_t;

/* ===================== API ===================== */

/**
 * Initialize database - clear all entries.
 * Must be called once at startup.
 */
void auth_db_init(void);

/**
 * Register a device by TID hex string.
 * Computes CRC32 as unique identifier.
 * Returns status and fills crc32_out.
 */
auth_db_status_t auth_db_register(const char *tid_hex, uint32_t *crc32_out);

/**
 * Re-synchronize the runtime tables with the current whitelist.
 *
 * The tables are indexed by whitelist position, so a reload that reorders or
 * shrinks the list leaves them bound to the wrong TIDs. Called by
 * auth_db_load_whitelist() after every reload; slots whose TID is unchanged are
 * left untouched so an in-flight authentication keeps its context.
 */
void auth_db_rebind_whitelist(void);

/**
 * Find device index by TID hex string.
 * Returns index or -1 if not found.
 */
int auth_db_find_by_tid(const char *tid_hex);

/**
 * Find device index by CRC32.
 * Returns index or -1 if not found.
 */
int auth_db_find_by_crc32(uint32_t crc32);

/**
 * Resolve CRC32 -> TID hex string.
 * tid_hex_out must be at least AUTH_DB_TID_HEX_LEN+1 bytes.
 */
auth_db_status_t auth_db_resolve(uint32_t crc32, char *tid_hex_out);

/**
 * Get authentication context for a device by CRC32.
 * Returns pointer to context or NULL if not found.
 */
auth_ctx_t *auth_db_get_ctx(uint32_t crc32);

/**
 * Reset authentication context for a device - start new auth session.
 */
auth_db_status_t auth_db_reset_ctx(uint32_t crc32);

#endif /* AUTH_DB_H */